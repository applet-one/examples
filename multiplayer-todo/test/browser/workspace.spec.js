import { test, expect } from '@playwright/test';

test('first-run onboarding, two browsers, comments, assignments, mobile and revocation', async ({ page, browser }, testInfo) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('#setup-name')).toBeVisible();
  await page.locator('#setup-name').fill('Alex Morgan');
  await page.getByRole('button', { name: 'Create list', exact: true }).click();
  await expect(page.locator('#enter-workspace')).toBeVisible();
  const adminURL = page.url();
  await page.locator('#enter-workspace').click();
  await expect(page.locator('#connection')).toHaveText('Live');
  await expect(page.locator('#connection')).toBeHidden();
  await expect(page.locator('#view-title')).toHaveText('All tasks');
  await expect(page.locator('.stats, .heading-art, .sidebar-note')).toHaveCount(0);
  await page.locator('#new-title').fill('Make something worth sharing');
  await page.locator('#add-form button').click();
  await expect(page.locator('.task-row')).toHaveCount(1);
  await expect(page.locator('#people-button')).toHaveCount(0);
  await page.locator('#profile').click();
  await page.locator('#invite-name').fill('Sam Rivera');
  await page.locator('#invite-form button').click();
  const collaboratorRow = page.locator('.person-row').filter({ hasText: 'Sam Rivera' });
  const collaboratorURL = await collaboratorRow.locator('input').inputValue();
  expect(await page.locator('#people-rows').evaluate(el => el.compareDocumentPosition(document.querySelector('#invite-form')) & Node.DOCUMENT_POSITION_FOLLOWING)).toBeTruthy();
  await page.reload();
  await page.locator('#profile').click();
  await expect(page.locator('.person-row').filter({ hasText: 'Sam Rivera' }).locator('input')).toHaveValue(collaboratorURL);
  await page.screenshot({ path: testInfo.outputPath('people-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Close people', exact: true }).click();
  const context = await browser.newContext();
  const other = await context.newPage();
  await other.goto(collaboratorURL);
  await expect(other.locator('#connection')).toHaveText('Live');
  await expect(other.locator('.task-row')).toHaveCount(1);
  await other.locator('#profile').click();
  await expect(other.locator('#invite-form')).toBeHidden();
  await expect(other.locator('#people-rows input')).toHaveCount(1);
  await expect(other.locator('#people-rows input')).toHaveValue(collaboratorURL);
  await other.getByRole('button', { name: 'Close people', exact: true }).click();
  await other.locator('.task-title').click();
  await other.locator('[data-assign]').filter({ hasText: 'Sam Rivera' }).click();
  await other.locator('#comment-text').fill('<script>not executable</script> Great idea!');
  await other.locator('#comment-form button').click();
  await expect(other.locator('.comment p')).toHaveText('<script>not executable</script> Great idea!');
  await expect(other.locator('#comment-text')).toHaveValue('');
  await page.locator('.task-title').click();
  await expect(page.locator('.comment strong')).toHaveText('Sam Rivera');
  await expect(page.locator('[data-assign].selected')).toContainText('Sam Rivera');
  await page.locator('#comment-text').fill('An unfinished thought');
  await other.locator('#detail-toggle').click();
  await expect(page.locator('#detail-toggle')).toContainText('Completed');
  await expect(page.locator('#comment-text')).toHaveValue('An unfinished thought');
  await page.locator('#detail-toggle').click();
  await page.getByRole('button', { name: 'Close task', exact: true }).click();
  await other.getByRole('button', { name: 'Close task', exact: true }).click();
  // Add a few real tasks to inspect the layout without injecting fake server data.
  for (const title of ['Sketch out the next big idea', 'Bring the team into the loop', 'Celebrate the small wins']) {
    await page.locator('#new-title').fill(title); await page.locator('#add-form button').click();
    await expect(page.locator('#new-title')).toHaveValue('');
  }
  await expect(other.locator('.task-row')).toHaveCount(4);
  await page.screenshot({ path: testInfo.outputPath('desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#new-title')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('mobile.png'), fullPage: true });
  expect(await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).map(el => ({ tag: el.tagName, class: el.className, right: el.getBoundingClientRect().right })))).toEqual([]);
  await page.locator('#profile').click();
  await page.screenshot({ path: testInfo.outputPath('people-mobile.png'), fullPage: true });
  expect(await page.locator('#people-dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-revoke]').click();
  await expect(other.locator('#gate')).toBeVisible();
  await expect(other.locator('#workspace')).toBeHidden();
  await other.reload();
  await expect(other.locator('#gate-content')).toContainText('invalid or has been revoked');
  await other.goto('/');
  await expect(other.locator('#gate-content h1')).toHaveText('Invite required');
  await expect(other.locator('#gate-content p')).toHaveCount(1);
  await expect(other.locator('.eyebrow, .gate-foot')).toHaveCount(0);
  await expect(page.locator('.person-row').filter({ hasText: 'Sam Rivera' })).toContainText('Access revoked');
  await page.getByRole('button', { name: 'Generate invite', exact: true }).click();
  const restoredRow = page.locator('.person-row').filter({ hasText: 'Sam Rivera' });
  await expect(restoredRow.locator('input')).toBeVisible();
  const restoredURL = await restoredRow.locator('input').inputValue();
  expect(restoredURL).not.toBe(collaboratorURL);
  await expect(page.locator('.person-row')).toHaveCount(2);
  await expect(page.locator('.legacy-link, [data-reset-link]')).toHaveCount(0);
  await other.goto(collaboratorURL);
  await expect(other.locator('#gate-content')).toContainText('invalid or has been revoked');
  await other.goto(restoredURL);
  await expect(other.locator('.task-row')).toHaveCount(4);
  await other.locator('.task-title').filter({ hasText: 'Make something worth sharing' }).click();
  await expect(other.locator('.comment strong')).toHaveText('Sam Rivera');
  await page.getByRole('button', { name: 'Close people', exact: true }).click();
  await page.goto(adminURL);
  await expect(page.locator('.task-row')).toHaveCount(4);
  expect(errors).toEqual([]);
  await context.close();
});
