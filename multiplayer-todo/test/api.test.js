import { test } from 'node:test';
import assert from 'node:assert/strict';

const base = process.env.TEST_URL;
test('real Worker: atomic setup, private tokens, live updates and revocation', { skip: !base }, async () => {
  const call = async (path, token, body) => {
    const response = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers: { ...(token ? { authorization: 'Bearer ' + token } : {}), ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  };
  assert.deepEqual((await call('/api/bootstrap')).body, { initialized: false }, 'Use a fresh local workspace for this test.');
  const tokens = ['a'.repeat(64), 'b'.repeat(64)];
  const claims = await Promise.all(tokens.map((token, i) => call('/api/setup', token, { name: 'Admin ' + i })));
  assert.deepEqual(claims.map(x => x.status).sort(), [201, 409]);
  const admin = tokens[claims.findIndex(c => c.status === 201)];
  assert.equal((await call('/api/state')).status, 401);
  const invite = await call('/api/invite', admin, { name: 'Sam' });
  assert.equal(invite.status, 201);
  const collaborator = invite.body.token;
  assert.equal((await call('/api/invite', collaborator, { name: 'Intruder' })).status, 403);
  assert.equal((await call('/api/links/restore', collaborator, { id: invite.body.memberId })).status, 403);
  assert.equal((await call('/api/state', admin)).body.members.find(m => m.id === invite.body.memberId).linkToken, collaborator);
  assert.ok((await call('/api/state', collaborator)).body.members.every(m => !('linkToken' in m)));
  const ws = new WebSocket(base.replace(/^http/, 'ws') + '/api/live?token=' + collaborator);
  const messages = [];
  ws.addEventListener('message', event => messages.push(JSON.parse(event.data)));
  await new Promise((resolve, reject) => { ws.addEventListener('open', resolve, { once: true }); ws.addEventListener('error', reject, { once: true }); });
  const waitFor = async check => { const deadline = Date.now() + 5000; while (!check()) { if (Date.now() > deadline) throw new Error('Timed out waiting for live update'); await new Promise(r => setTimeout(r, 30)); } };
  const created = await call('/api/tasks', admin, { action: 'create', title: 'Plan together' });
  const id = created.body.tasks[0].id;
  await waitFor(() => messages.some(m => m.tasks.some(t => t.id === id)));
  await call('/api/tasks', collaborator, { action: 'update', id, assignees: [invite.body.memberId], completed: true });
  const comment = await call('/api/comments', collaborator, { id, text: '<b>Great!</b>', name: 'Admin' });
  assert.equal(comment.body.tasks[0].comments[0].name, 'Sam');
  assert.equal(JSON.stringify(comment.body).includes('hash'), false);
  const closed = new Promise(resolve => ws.addEventListener('close', resolve, { once: true }));
  await call('/api/revoke', admin, { id: invite.body.memberId });
  assert.equal((await closed).code, 4001);
  assert.ok(messages.every(s => s.members.every(m => !('linkToken' in m))));
  assert.equal((await call('/api/state', collaborator)).status, 401);
  assert.ok(!(await call('/api/state', admin)).body.members.find(m => m.id === invite.body.memberId).linkToken);
  assert.equal((await call('/api/tasks', collaborator, { action: 'delete', id })).status, 401);
  assert.deepEqual((await call('/api/state', admin)).body.tasks[0].assignees, []);
  const adminId = (await call('/api/state', admin)).body.me;
  assert.equal((await call('/api/links/restore', admin, { id: adminId })).status, 400);
  assert.equal((await call('/api/links/restore', admin, { id: 'missing' })).status, 404);
  const restored = await call('/api/links/restore', admin, { id: invite.body.memberId });
  assert.equal(restored.status, 200);
  assert.equal(restored.body.memberId, invite.body.memberId);
  assert.notEqual(restored.body.token, collaborator);
  assert.equal(restored.body.state.members.length, 2);
  assert.equal((await call('/api/state', collaborator)).status, 401);
  assert.equal((await call('/api/state', invite.body.token)).status, 401);
  const returned = await call('/api/state', restored.body.token);
  assert.equal(returned.status, 200);
  assert.equal(returned.body.me, invite.body.memberId);
  assert.equal(returned.body.tasks[0].comments[0].userId, invite.body.memberId);
  assert.equal((await call('/api/links/restore', restored.body.token, { id: invite.body.memberId })).status, 403);
  assert.equal((await call('/api/links/restore', admin, { id: invite.body.memberId })).status, 409);
  const crossSite = await fetch(base + '/api/tasks', { method: 'POST', headers: { authorization: 'Bearer ' + admin, 'content-type': 'application/json', origin: 'https://evil.example' }, body: JSON.stringify({ action: 'create', title: 'No' }) });
  assert.equal(crossSite.status, 403);
  const malformed = await fetch(base + '/api/tasks', { method: 'POST', headers: { authorization: 'Bearer ' + admin, 'content-type': 'application/json' }, body: 'null' });
  assert.equal(malformed.status, 400);
});
