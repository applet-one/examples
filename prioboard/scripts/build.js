import { build } from "esbuild";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["client/main.js"],
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "inline",
});
const assets = {
  "/": {
    type: "text/html; charset=utf-8",
    content: await readFile(`${root}client/index.html`, "utf8"),
  },
  "/assets/styles.css": {
    type: "text/css; charset=utf-8",
    content: await readFile(`${root}client/styles.css`, "utf8"),
  },
  "/assets/main.js": {
    type: "text/javascript; charset=utf-8",
    content: result.outputFiles[0].text,
  },
};
await mkdir(`${root}generated`, { recursive: true });
await writeFile(
  `${root}generated/assets.js`,
  `// Generated by npm run build. Do not edit.\nexport const assets = ${JSON.stringify(assets)};\n`,
);
console.log("Built browser assets into generated/assets.js");
